-- Product Lab - Process Mapping + Requirements Management
-- Target: PostgreSQL
-- IMPORTANT:
-- 1) Adjust foreign keys to the real Product Lab tables (Product, Feature, User Story, Business Area, User)
--    before enabling them in production.
-- 2) This script uses TEXT + CHECK constraints instead of PostgreSQL ENUM types to keep schema evolution simpler.

BEGIN;

-- =========================================================
-- HELPER: updated_at trigger
-- =========================================================

CREATE OR REPLACE FUNCTION fn_set_updated_at()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at = CURRENT_TIMESTAMP;
    RETURN NEW;
END;
$$;

-- =========================================================
-- PROCESS MAPPING
-- =========================================================

CREATE TABLE IF NOT EXISTS process (
    process_id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id              BIGINT NULL,
    business_area_id        BIGINT NULL,
    process_name            VARCHAR(200) NOT NULL,
    process_description     TEXT NULL,
    process_version         VARCHAR(30) NOT NULL DEFAULT '1.0',
    process_type            VARCHAR(20) NOT NULL DEFAULT 'AS_IS',
    process_status          VARCHAR(20) NOT NULL DEFAULT 'DRAFT',
    process_owner           VARCHAR(150) NULL,
    process_trigger         TEXT NULL,
    process_outcome         TEXT NULL,
    created_by              BIGINT NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_by              BIGINT NULL,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    is_deleted              BOOLEAN NOT NULL DEFAULT FALSE,
    CONSTRAINT ck_process_type CHECK (process_type IN ('AS_IS','TO_BE')),
    CONSTRAINT ck_process_status CHECK (process_status IN ('DRAFT','VALIDATED','APPROVED','ARCHIVED')),
    CONSTRAINT uq_process_name_version UNIQUE (product_id, process_name, process_version)
);

CREATE INDEX IF NOT EXISTS ix_process_product
    ON process(product_id);
CREATE INDEX IF NOT EXISTS ix_process_business_area
    ON process(business_area_id);
CREATE INDEX IF NOT EXISTS ix_process_status
    ON process(process_status);
CREATE INDEX IF NOT EXISTS ix_process_type
    ON process(process_type);

DROP TRIGGER IF EXISTS trg_process_updated_at ON process;
CREATE TRIGGER trg_process_updated_at
BEFORE UPDATE ON process
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

CREATE TABLE IF NOT EXISTS processnode (
    node_id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_id              BIGINT NOT NULL,
    node_type               VARCHAR(30) NOT NULL,
    node_title              VARCHAR(200) NOT NULL,
    node_description        TEXT NULL,
    role_name               VARCHAR(150) NULL,
    business_area_id        BIGINT NULL,
    system_name             VARCHAR(150) NULL,
    duration_minutes        NUMERIC(12,2) NULL,
    is_manual               BOOLEAN NOT NULL DEFAULT FALSE,
    is_bottleneck           BOOLEAN NOT NULL DEFAULT FALSE,
    x_position              NUMERIC(12,2) NOT NULL DEFAULT 0,
    y_position              NUMERIC(12,2) NOT NULL DEFAULT 0,
    width                   NUMERIC(12,2) NULL,
    height                  NUMERIC(12,2) NULL,
    display_order           INTEGER NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_processnode_type CHECK (
        node_type IN ('START','ACTIVITY','DECISION','END','SUBPROCESS','SYSTEM','WAIT','HANDOFF')
    ),
    CONSTRAINT fk_processnode_process
        FOREIGN KEY (process_id) REFERENCES process(process_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_processnode_process
    ON processnode(process_id);
CREATE INDEX IF NOT EXISTS ix_processnode_type
    ON processnode(node_type);
CREATE INDEX IF NOT EXISTS ix_processnode_business_area
    ON processnode(business_area_id);

DROP TRIGGER IF EXISTS trg_processnode_updated_at ON processnode;
CREATE TRIGGER trg_processnode_updated_at
BEFORE UPDATE ON processnode
FOR EACH ROW EXECUTE FUNCTION fn_set_updated_at();

CREATE TABLE IF NOT EXISTS processedge (
    edge_id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    process_id              BIGINT NOT NULL,
    source_node_id          BIGINT NOT NULL,
    target_node_id          BIGINT NOT NULL,
    edge_label              VARCHAR(150) NULL,
    edge_type               VARCHAR(20) NOT NULL DEFAULT 'SEQUENCE',
    condition_expression    TEXT NULL,
    sequence_order          INTEGER NULL,
    created_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT ck_processedge_type CHECK (
        edge_type IN ('SEQUENCE','CONDITIONAL','DEFAULT','EXCEPTION')
    ),
    CONSTRAINT chk_processedge_nodes CHECK (source_node_id <> target_node_id),
    CONSTRAINT fk_processedge_process
        FOREIGN KEY (process_id) REFERENCES process(process_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_processedge_source
        FOREIGN KEY (source_node_id) REFERENCES processnode(node_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE,
    CONSTRAINT fk_processedge_target
        FOREIGN KEY (target_node_id) REFERENCES processnode(node_id)
        ON DELETE CASCADE
        ON UPDATE CASCADE
);

CREATE INDEX IF NOT EXISTS ix_processedge_process
    ON processedge(process_id);
CREATE INDEX IF NOT EXISTS ix_processedge_source
    ON processedge(source_node_id);
CREATE INDEX IF NOT EXISTS ix_processedge_target
    ON processedge(target_node_id);

DROP TRIGGER IF EXISTS trg_processedge_updated_at ON processedge;
CREATE TRIGGER trg_processedge_updated_at
