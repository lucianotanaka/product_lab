CREATE OR REPLACE VIEW vwRequirementCoverage AS
SELECT
    r.requirement_id,
    r.product_id,
    r.requirement_code,
    r.requirement_title,
    r.requirement_type,
    r.priority,
    r.lifecycle_status,
    r.fulfillment_status,
    COUNT(DISTINCT rf.feature_id) AS feature_count,
    COUNT(DISTINCT rus.user_story_id) AS user_story_count,
    COUNT(DISTINCT rus.user_story_id) FILTER (WHERE rus.coverage_status = 'COVERED') AS covered_story_count,
    CASE
        WHEN BOOL_OR(rv.verification_result = 'PASS') THEN 1
        ELSE 0
    END AS has_pass_verification
FROM requirement r
LEFT JOIN requirementfeature rf
    ON rf.requirement_id = r.requirement_id
LEFT JOIN requirementuserstory rus
    ON rus.requirement_id = r.requirement_id
LEFT JOIN requirementverification rv
    ON rv.requirement_id = r.requirement_id
WHERE r.is_deleted = FALSE
GROUP BY
    r.requirement_id,
    r.product_id,
    r.requirement_code,
    r.requirement_title,
    r.requirement_type,
    r.priority,
    r.lifecycle_status,
    r.fulfillment_status;

CREATE OR REPLACE VIEW vwProcessSummary AS
SELECT
    p.process_id,
    p.product_id,
    p.process_name,
    p.process_version,
    p.process_type,
    p.process_status,
    COUNT(DISTINCT n.node_id) AS node_count,
    COUNT(DISTINCT e.edge_id) AS edge_count,
    COUNT(DISTINCT n.node_id) FILTER (WHERE n.is_manual = TRUE) AS manual_node_count,
    COUNT(DISTINCT n.node_id) FILTER (WHERE n.is_bottleneck = TRUE) AS bottleneck_count
FROM process p
LEFT JOIN processnode n
    ON n.process_id = p.process_id
LEFT JOIN processedge e
    ON e.process_id = p.process_id
WHERE p.is_deleted = FALSE
GROUP BY
    p.process_id,
    p.product_id,
    p.process_name,
    p.process_version,
    p.process_type,
    p.process_status;

COMMIT;
